/**
 * SkillSystem — Off-field Commander passive bonuses, Ultimate Energy accounting
 * (strictly separate from Command Energy), and full battlefield ultimate execution.
 */

export class SkillSystem {
  constructor({ gameState, heroSystem, eventBus, dataRegistry = null }) {
    this._state = gameState;
    this._heroes = heroSystem;
    this._eventBus = eventBus;
    this._data = dataRegistry;
    this._activating = false;
  }

  getActiveCommanderSkills() {
    const commander = this._heroes.getActiveCommander();
    return {
      commander,
      passive: commander?.passiveSkill || null,
      ultimate: commander?.ultimateSkill || null,
    };
  }

  getCommandEnergyRegenMultiplier() {
    const { passive } = this.getActiveCommanderSkills();
    if (
      passive?.effect &&
      (passive.effect.stat === 'energyRegen' || passive.effect.stat === 'dpRegen')
    ) {
      return 1 + (passive.effect.value || 0);
    }
    return 1.0;
  }

  /**
   * Adds Ultimate Energy generated by active living friendly units (damage dealt,
   * damage received, healing performed). Caps at ultimateMaxEnergy (100).
   */
  addUltimateEnergy(amount) {
    if (!Number.isFinite(amount) || amount <= 0) return;
    const { commander } = this.getActiveCommanderSkills();
    const scale = commander?.baseStats?.energyRegen ?? 1.0;
    const current = this._state.battle.ultimateEnergy || 0;
    const max = this._state.battle.ultimateMaxEnergy || 100;
    if (current >= max) return;

    const next = Math.min(max, current + amount * scale);
    this._state.setBattle({ ultimateEnergy: next });
  }

  canActivateUltimate() {
    if (this._activating) return false;
    const b = this._state.battle;
    if (b.status !== 'running' && b.phase !== 'active_combat' && b.phase !== 'wave_transition') {
      return false;
    }
    return b.ultimateEnergy >= b.ultimateMaxEnergy;
  }

  /**
   * Activates the Commander's ultimate ability, consuming 100 Ultimate Energy and
   * resolving real combat damage, healing, shields, and buffs through CombatSystem.
   * When `deferDamage` is true (e.g., Astra's staged Starfall Judgment), enemy damage
   * is deferred onto the synchronized impact waves while healing/buffs resolve cleanly.
   */
  activateUltimate({ unitManager = null, combatSystem = null, deferDamage = false } = {}) {
    if (this._activating) {
      return { ok: false, reason: 'Ultimate is already activating.' };
    }
    if (this._state.battle.ultimateEnergy < this._state.battle.ultimateMaxEnergy) {
      return { ok: false, reason: 'Ultimate energy is still charging (requires 100).' };
    }

    const { commander, ultimate } = this.getActiveCommanderSkills();
    if (!ultimate) {
      return { ok: false, reason: 'Commander has no configured ultimate ability.' };
    }

    this._activating = true;
    this._state.setBattle({ ultimateEnergy: 0 });

    const eff = ultimate.effect || {};
    const cmdScale = 1 + Math.max(0, (commander?.level || 1) - 1) * 0.08;
    const summary = {
      enemiesHit: 0,
      alliesHealed: 0,
      alliesBuffed: 0,
      totalDamage: 0,
      totalHeal: 0,
    };

    if (unitManager && combatSystem) {
      const durationSec = eff.durationSec || 8;
      const rawDamage = eff.damage ? Math.round(eff.damage * cmdScale) : 0;

      if (deferDamage && rawDamage > 0) {
        summary.stagedDamage = true;
        summary.pendingRawDamage = rawDamage;
        summary.attackType = eff.attackType || 'magical';
        summary.armorPierce = eff.armorPierce || 0;
      }

      // Damage & debuff all living enemies (Seraphina, Kael, or non-deferred Astra)
      if ((!deferDamage && rawDamage > 0) || eff.slowEnemies || eff.defenseShred) {
        const enemies = unitManager.getBySide('enemy');
        for (const enemy of enemies) {
          if (!deferDamage && rawDamage > 0) {
            const res = combatSystem.applyDamage({
              source: null, // Commander off-field strike does not refund own ultimate energy
              target: enemy,
              rawAttack: rawDamage,
              attackType: eff.attackType || 'magical',
              armorPierce: eff.armorPierce || 0,
              critChance: 0,
              unitManager,
              skillSystem: null,
            });
            if (res.applied) {
              summary.enemiesHit += 1;
              summary.totalDamage += res.amount;
            }
          }
          if (enemy.hp > 0 && enemy.state !== 'Dead') {
            if (eff.slowEnemies) {
              unitManager.applyStatusEffect(enemy, {
                id: `${ultimate.id}_slow`,
                type: 'debuff_slow',
                value: eff.slowEnemies,
                durationSec,
              });
            }
            if (eff.defenseShred) {
              unitManager.applyStatusEffect(enemy, {
                id: `${ultimate.id}_shred`,
                type: 'debuff_defense',
                value: eff.defenseShred,
                durationSec,
              });
            }
          }
        }
      }

      // Cleanse & Heal all living friendly units (ASTRA Starfall Judgment, Lyra Sanctuary Pulse)
      const allies = unitManager.getBySide('ally');
      if (eff.cleanseAllies && typeof unitManager.cleanseDebuffs === 'function') {
        for (const ally of allies) {
          unitManager.cleanseDebuffs(ally);
        }
      }

      if (eff.healAmount && eff.healAmount > 0) {
        const rawHeal = Math.round(eff.healAmount * cmdScale);
        for (const ally of allies) {
          const res = combatSystem.applyHeal({
            source: null,
            target: ally,
            rawHeal,
            skillSystem: null,
          });
          if (res.applied) {
            summary.alliesHealed += 1;
            summary.totalHeal += res.amount;
          }
        }
      }

      // Apply army-wide buffs/shields (Kael, Lyra, Orin Vance)
      for (const ally of allies) {
        let buffed = false;
        if (eff.attackBuff) {
          unitManager.applyStatusEffect(ally, {
            id: `${ultimate.id}_atk`,
            type: 'buff_attack',
            value: eff.attackBuff,
            durationSec,
          });
          buffed = true;
        }
        if (eff.speedBuff) {
          unitManager.applyStatusEffect(ally, {
            id: `${ultimate.id}_spd`,
            type: 'buff_speed',
            value: eff.speedBuff,
            durationSec,
          });
          buffed = true;
        }
        if (eff.defenseBuff) {
          unitManager.applyStatusEffect(ally, {
            id: `${ultimate.id}_def`,
            type: 'buff_defense',
            value: eff.defenseBuff,
            durationSec,
          });
          buffed = true;
        }
        if (eff.shieldAmount) {
          unitManager.applyStatusEffect(ally, {
            id: `${ultimate.id}_shd`,
            type: 'shield',
            value: Math.round(eff.shieldAmount * cmdScale),
            durationSec,
          });
          buffed = true;
        }
        if (buffed) summary.alliesBuffed += 1;
      }
    }

    // Command Energy grant (e.g. Orin Vance Fortified Line)
    if (eff.commandEnergyGain && eff.commandEnergyGain > 0) {
      const nextEnergy = Math.min(
        this._state.battle.maxEnergy || 100,
        (this._state.battle.energy || 0) + eff.commandEnergyGain,
      );
      this._state.setBattle({ energy: nextEnergy, dp: nextEnergy });
      summary.commandEnergyGained = eff.commandEnergyGain;
    }

    this._eventBus?.emit('commander:ultimateActivated', {
      commander,
      skill: ultimate,
      summary,
    });

    this._activating = false;
    return { ok: true, commander, skill: ultimate, summary };
  }

  update() {
    // Ultimate energy is earned strictly from active combat actions (damage dealt,
    // damage received, healing performed) rather than unconditional passive ticking.
  }
}
