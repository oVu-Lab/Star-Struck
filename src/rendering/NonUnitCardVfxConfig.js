export const NON_UNIT_CARD_IDS = Object.freeze(Object.keys(NON_UNIT_CARD_VFX_PROFILES));

export const NON_UNIT_WORLD_FX_KINDS = new Set(
  Object.values(NON_UNIT_CARD_VFX_PROFILES).map((p) => p.worldFxKind),
);

export function isNonUnitCard(card) {
  if (!card || typeof card !== 'object') return false;
  return NON_UNIT_CATEGORIES.includes(card.category);
}

export function getNonUnitCardVfxProfile(cardOrId) {
  if (!cardOrId) return null;
  if (typeof cardOrId === 'string') {
    return NON_UNIT_CARD_VFX_PROFILES[cardOrId] || null;
  }
  if (!isNonUnitCard(cardOrId)) return null;
  if (cardOrId.cardId && NON_UNIT_CARD_VFX_PROFILES[cardOrId.cardId]) {
    return NON_UNIT_CARD_VFX_PROFILES[cardOrId.cardId];
  }
  // Safe fallback for any future non-Unit card based on category
  if (cardOrId.category === 'skill') return NON_UNIT_CARD_VFX_PROFILES.card_skill_astral_nova;
  if (cardOrId.category === 'tactic') return NON_UNIT_CARD_VFX_PROFILES.card_tactic_full_assault;
  if (cardOrId.category === 'support') return NON_UNIT_CARD_VFX_PROFILES.card_support_aegis_blessing;
  return null;
}
