  heavy_defender: 'heavy_shield_guard',
  swift_cavalry: 'wind_cavalry',
  arcane_archer: 'arcane_archer',
  field_cleric: 'field_cleric',
  anti_armor_melee: 'vanguard_breaker',
  fast_ranged: 'pulse_skirmisher',
